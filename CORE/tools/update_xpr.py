#!/usr/bin/env python3
# -----------------------------------------------------------------------------
# TRS-80 for MEGA65
#
# Updates the source lists of the Vivado projects CORE/CORE-R*.xpr:
#   * removes the M2M democore and the template's keyboard.vhd
#   * adds the TRS-80 MiSTer core (file list taken from the core's Quartus
#     files.qip), without the files that are replaced by the MEGA65 versions
#     in CORE/vhdl/trs80 and without the files that are replaced by the
#     patched copies in CORE/vhdl/trs80_patched (see CORE/patches)
#   * adds the MEGA65 specific TRS-80 files in CORE/vhdl/trs80 and
#     CORE/vhdl/m65_keyboard.vhd
#
# The files of the MiSTer core (and the patched copies) are compiled as VHDL-93
# (like Quartus does),
# the MEGA65 specific files as VHDL-2008.
#
# The script is idempotent. Run it after updating the TRS-80_MiSTer submodule:
#    python3 CORE/tools/update_xpr.py
#
# Based on the project updater of the X68000 port (MegaX68000).
# TRS-80 port 2026, licensed under GPL v3
# -----------------------------------------------------------------------------

import os
import re

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
CORE = os.path.join(ROOT, "CORE")
MISTER = os.path.join(CORE, "TRS-80_MiSTer")

# replaced by MEGA65 specific files
REPLACED = {
    "rtl/keyboard.sv",      # CORE/vhdl/trs80/keyboard_matrix.vhd
    "rtl/sprom.vhd",        # CORE/vhdl/trs80/sprom.vhd (altsyncram)
    "TRS-80.sv",            # MiSTer top level, replaced by CORE/vhdl/trs80/trs80_top.sv
}

# MEGA65 specific TRS-80 files (order matters for packages)
OWN_DIRS = ["vhdl/trs80", "vhdl/trs80_patched"]
PATCHED = os.path.join(CORE, "vhdl", "trs80_patched")
OWN_FIRST = ["vhdl/trs80/trs80_menu_pkg.vhd"]
OWN_EXTRA = ["vhdl/m65_keyboard.vhd"]

MARK_BEGIN = "<!-- TRS-80 sources: begin (generated by CORE/tools/update_xpr.py) -->"
MARK_END = "<!-- TRS-80 sources: end -->"


def parse_qip(path):
    out = []
    for line in open(path):
        m = re.search(r'-name\s+(\w+)\s+(?:\[file join \$::quartus\(qip_path\)\s+"?(\S+?)"?\s*\]|(\S+))', line)
        if not m:
            continue
        kind = m.group(1)
        p = m.group(2) or m.group(3)
        if kind not in ("QIP_FILE", "VHDL_FILE", "VERILOG_FILE", "SYSTEMVERILOG_FILE"):
            continue
        if "qip_path" in line:
            p = os.path.normpath(os.path.join(os.path.dirname(path), p))
        else:
            p = os.path.normpath(os.path.join(MISTER, p))
        if kind == "QIP_FILE":
            out += parse_qip(p)
        else:
            out.append(p)
    return out


def file_entry(path):
    rel = "$PPRDIR/" + os.path.relpath(path, CORE)
    ext = os.path.splitext(path)[1].lower()
    own = not path.startswith(MISTER + os.sep) and not path.startswith(PATCHED + os.sep)
    if ext == ".vhd":
        info = '<FileInfo SFType="VHDL2008">' if own else "<FileInfo>"
    elif ext == ".sv":
        info = '<FileInfo SFType="SVerilog">'
    else:
        info = "<FileInfo>"
    return ('      <File Path="%s">\n'
            '        %s\n'
            '          <Attr Name="UsedIn" Val="synthesis"/>\n'
            '          <Attr Name="UsedIn" Val="implementation"/>\n'
            '          <Attr Name="UsedIn" Val="simulation"/>\n'
            '        </FileInfo>\n'
            '      </File>\n') % (rel, info)


def sources():
    patched = {os.path.basename(f) for f in os.listdir(PATCHED)}
    files = []
    for f in parse_qip(os.path.join(MISTER, "files.qip")):
        rel = os.path.relpath(f, MISTER)
        if rel in REPLACED:
            continue
        if os.path.basename(f) in patched:
            continue
        assert os.path.exists(f), f
        files.append(f)
    own = [os.path.join(CORE, f) for f in OWN_FIRST]
    for d in OWN_DIRS:
        for fn in sorted(os.listdir(os.path.join(CORE, d))):
            p = os.path.join(CORE, d, fn)
            if p not in own and os.path.splitext(fn)[1] in (".vhd", ".v", ".sv", ".mem"):
                own.append(p)
    own += [os.path.join(CORE, f) for f in OWN_EXTRA]
    return own + files


def update(xpr):
    s = open(xpr).read()
    # remove previously generated block
    s = re.sub(r"\s*" + re.escape(MARK_BEGIN) + r".*?" + re.escape(MARK_END), "", s, flags=re.S)
    # remove the democore and the template's keyboard.vhd (replaced by vhdl/m65_keyboard.vhd)
    s = re.sub(r'\s*<File Path="\$PPRDIR/\.\./M2M/vhdl/democore/[^"]*">.*?</File>', "", s, flags=re.S)
    s = re.sub(r'\s*<File Path="\$PPRDIR/vhdl/keyboard\.vhd">.*?</File>', "", s, flags=re.S)
    block = "\n      " + MARK_BEGIN + "\n" + "".join(file_entry(f) for f in sources()) + "      " + MARK_END
    # insert at the end of the sources_1 file set (before its <Config>)
    i = s.index('<FileSet Name="sources_1"')
    j = s.index("<Config>", i)
    k = s.rindex("\n", i, j)
    s = s[:k] + block + s[k:]
    open(xpr, "w").write(s)
    return len(sources())


if __name__ == "__main__":
    for r in ("R3", "R4", "R5", "R6"):
        xpr = os.path.join(CORE, "CORE-%s.xpr" % r)
        if os.path.exists(xpr):
            print("%s: %d TRS-80 files" % (os.path.basename(xpr), update(xpr)))
